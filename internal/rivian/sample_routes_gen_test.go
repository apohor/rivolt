//go:build samplegen

// Generates sample_routes_gen.go: the road shape of every leg the sample
// truck drives, from a Valhalla routing service. Run by hand, never in
// CI, so the corpus itself stays offline and deterministic:
//
//	SAMPLEGEN_VALHALLA=http://localhost:18081 go test -tags samplegen -run TestGenerateSampleRoutes ./internal/rivian
//
// The legs join public landmarks only (sample_corpus.go), so the shapes
// hold no one's location history.
package rivian

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"math"
	"net/http"
	"os"
	"sort"
	"testing"
	"time"
)

// routeSimplifyM: shape points closer than this to the simplified line
// are dropped (Douglas–Peucker), keeping the file small.
const routeSimplifyM = 20.0

func TestGenerateSampleRoutes(t *testing.T) {
	base := os.Getenv("SAMPLEGEN_VALHALLA")
	if base == "" {
		t.Skip("SAMPLEGEN_VALHALLA not set")
	}
	c := NewSampleCorpus(SampleSeed)
	legs := map[string][2]samplePoint{}
	for _, l := range c.legs {
		legs[routeKey(l[0], l[1])] = l
	}
	keys := make([]string, 0, len(legs))
	for k := range legs {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	client := &http.Client{Timeout: 60 * time.Second}
	var buf bytes.Buffer
	buf.WriteString("// Code generated by sample_routes_gen_test.go (go test -tags samplegen); DO NOT EDIT.\n\n")
	buf.WriteString("package rivian\n\n")
	buf.WriteString("// sampleRouteShapes are the road shapes of the sample truck's legs,\n")
	buf.WriteString("// keyed by routeKey(from, to), as Google encoded polylines (precision 5).\n")
	buf.WriteString("var sampleRouteShapes = map[string]string{\n")
	for _, k := range keys {
		l := legs[k]
		pts, miles, err := valhallaRoute(client, base, l[0], l[1])
		if err != nil {
			t.Fatalf("%s: %v", k, err)
		}
		simple := simplifyPath(pts, routeSimplifyM)
		enc := make([][2]float64, len(simple))
		for i, p := range simple {
			enc[i] = [2]float64{p.Lat, p.Lon}
		}
		fmt.Fprintf(&buf, "\t%q: %q, // %.1f mi, %d points\n", k, encodePolyline(enc), miles, len(simple))
		t.Logf("%s: %.1f mi, %d → %d points", k, miles, len(pts), len(simple))
	}
	buf.WriteString("}\n")
	src, err := format.Source(buf.Bytes())
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile("sample_routes_gen.go", src, 0o644); err != nil {
		t.Fatal(err)
	}
}

func valhallaRoute(client *http.Client, base string, from, to samplePoint) ([]samplePoint, float64, error) {
	body, _ := json.Marshal(map[string]any{
		"locations":          []map[string]float64{{"lat": from.Lat, "lon": from.Lon}, {"lat": to.Lat, "lon": to.Lon}},
		"costing":            "auto",
		"directions_options": map[string]string{"units": "miles"},
		"directions_type":    "none",
	})
	resp, err := client.Post(base+"/route", "application/json", bytes.NewReader(body))
	if err != nil {
		return nil, 0, err
	}
	defer resp.Body.Close()
	var out struct {
		Trip struct {
			Summary struct{ Length float64 }
			Legs    []struct{ Shape string }
		}
	}
	if err := json.NewDecoder(resp.Body).Decode(&out); err != nil {
		return nil, 0, err
	}
	if resp.StatusCode != http.StatusOK || len(out.Trip.Legs) == 0 {
		return nil, 0, fmt.Errorf("valhalla: status %d", resp.StatusCode)
	}
	return decodePolyline6(out.Trip.Legs[0].Shape), out.Trip.Summary.Length, nil
}

// decodePolyline6 decodes Valhalla's precision-6 encoded polyline.
func decodePolyline6(s string) []samplePoint {
	p5 := decodeSamplePolyline(s) // same algorithm, scaled for 1e5
	out := make([]samplePoint, len(p5))
	for i, p := range p5 {
		out[i] = samplePoint{p.Lat / 10, p.Lon / 10}
	}
	return out
}

// simplifyPath is Douglas–Peucker with tolerance tolM metres, on a local
// equirectangular projection.
func simplifyPath(p []samplePoint, tolM float64) []samplePoint {
	if len(p) < 3 {
		return p
	}
	keep := make([]bool, len(p))
	keep[0], keep[len(p)-1] = true, true
	var rec func(a, b int)
	rec = func(a, b int) {
		if b-a < 2 {
			return
		}
		worst, at := 0.0, -1
		for i := a + 1; i < b; i++ {
			if d := segDistM(p[i], p[a], p[b]); d > worst {
				worst, at = d, i
			}
		}
		if worst > tolM {
			keep[at] = true
			rec(a, at)
			rec(at, b)
		}
	}
	rec(0, len(p)-1)
	var out []samplePoint
	for i, k := range keep {
		if k {
			out = append(out, p[i])
		}
	}
	return out
}

func segDistM(p, a, b samplePoint) float64 {
	const mPerDeg = 111320.0
	k := math.Cos(a.Lat * math.Pi / 180)
	px, py := (p.Lon-a.Lon)*mPerDeg*k, (p.Lat-a.Lat)*mPerDeg
	bx, by := (b.Lon-a.Lon)*mPerDeg*k, (b.Lat-a.Lat)*mPerDeg
	l2 := bx*bx + by*by
	if l2 == 0 {
		return math.Hypot(px, py)
	}
	u := math.Max(0, math.Min(1, (px*bx+py*by)/l2))
	return math.Hypot(px-u*bx, py-u*by)
}
